"""
PDF Service
-----------
Generates a formatted clinical report PDF from confirmed appointment-prep
and / or approved hypothesis data.

Returns raw bytes (PDF).  Caller is responsible for streaming the response.

Layout
------
  Page header: Sukshma-Jignaasa | Clinical Report | date
  Section 1 : Symptom Overview   (always present when prep included)
  Section 2 : Trigger Patterns   (always present when prep included)
  Section 3 : Suggested Questions(always present when prep included)
  Section 4 : Summary Narrative  (always present when prep included)
  Section 5 : Pattern Analysis   (only when hypothesis included)
  Page footer: AI disclosure on every page

All text is plain-language; no clinical interpretation added by this service.
"""
from __future__ import annotations

import io
from datetime import datetime, timezone

from reportlab.lib import colors
from reportlab.lib.enums import TA_CENTER, TA_LEFT, TA_RIGHT
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import (
    HRFlowable,
    PageBreak,
    Paragraph,
    SimpleDocTemplate,
    Spacer,
    Table,
    TableStyle,
)

# ---------------------------------------------------------------------------
# Disclosure — identical to the one enforced in the model layer
# ---------------------------------------------------------------------------

_DISCLOSURE = (
    "Generated by Sukshma-Jignaasa AI companion. "
    "This is not a medical diagnosis and cannot replace a clinical evaluation. "
    "Share with your healthcare provider as a starting point for discussion."
)

_HYPOTHESIS_DISCLOSURE = (
    "The pattern profiles below highlight symptom similarities only. "
    "They are not a medical diagnosis and cannot replace a clinical evaluation. "
    "Please discuss any of these patterns with a specialist who can assess your full history."
)


