_BADGE_COLORS = {
    "high": colors.HexColor("#d32f2f"),
    "medium": colors.HexColor("#f57c00"),
    "low": colors.HexColor("#388e3c"),
}

_SEVERITY_BAR = "▓"  # filled block; we repeat it proportionally


def _severity_bar(avg: float) -> str:
    filled = round(avg)
    return _SEVERITY_BAR * filled + "░" * (10 - filled)


# ---------------------------------------------------------------------------
# Header / footer callback
# ---------------------------------------------------------------------------

def _make_header_footer(patient_id: str, generated_at: str):
    def _draw(canvas, doc):
        canvas.saveState()
        w, h = A4

        # Header line
        canvas.setStrokeColor(colors.HexColor("#1a1a2e"))
        canvas.setLineWidth(0.5)
        canvas.line(15 * mm, h - 18 * mm, w - 15 * mm, h - 18 * mm)

        canvas.setFont("Helvetica-Bold", 8)
        canvas.setFillColor(colors.HexColor("#1a1a2e"))
        canvas.drawString(15 * mm, h - 14 * mm, "Sukshma-Jignaasa  ·  Clinical Report")

        canvas.setFont("Helvetica", 7)
        canvas.setFillColor(colors.HexColor("#888888"))
        canvas.drawRightString(w - 15 * mm, h - 14 * mm, f"Generated: {generated_at}")

        # Footer line
        canvas.line(15 * mm, 18 * mm, w - 15 * mm, 18 * mm)
        canvas.setFont("Helvetica", 7)
        canvas.setFillColor(colors.HexColor("#888888"))
        canvas.drawString(15 * mm, 12 * mm, _DISCLOSURE)
        canvas.drawRightString(w - 15 * mm, 12 * mm, f"Page {doc.page}")
        canvas.restoreState()

    return _draw


